/**
 * v2.11.29 — WebView 51 (Android 7 / CS10) Capacitor bridge downlevel.
 *
 * Capacitor's native shell injects `native-bridge.js` INLINE into index.html at
 * startup. The shipped asset is ES2017 (`const x = async (y) => {}` at line 47),
 * which WebView 51 / Chromium 51 cannot parse:
 *
 *     Uncaught SyntaxError: Unexpected token (   (index.html:54)
 *
 * The inline script dies mid-parse, so `window.Capacitor.Plugins` is never fully
 * published and every plugin call fails with UNIMPLEMENTED / empty errors.
 *
 * Fix: transpile the bridge to ES5 and write it to
 * `android/app/src/main/assets/native-bridge.js`. Android app-module assets take
 * precedence over the Capacitor AAR asset, so the shell injects our ES5 copy.
 * node_modules is never mutated and Capacitor is not forked.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { transformAsync } from "@babel/core";
import * as acorn from "acorn";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");

const SOURCE = resolve(
  ROOT,
  "node_modules/@capacitor/android/capacitor/src/main/assets/native-bridge.js"
);
const TARGET = resolve(ROOT, "android/app/src/main/assets/native-bridge.js");

export async function buildLegacyBridge({ silent = false } = {}) {
  if (!existsSync(SOURCE)) {
    // Capacitor Android not installed (pure web checkout) — nothing to do.
    if (!silent) console.warn("[legacy-bridge] source not found, skipped:", SOURCE);
    return { skipped: true };
  }

  const source = readFileSync(SOURCE, "utf8");

  const result = await transformAsync(source, {
    filename: "native-bridge.js",
    babelrc: false,
    configFile: false,
    compact: false,
    sourceMaps: false,
    presets: [
      [
        "@babel/preset-env",
        {
          // Chromium 51 has generators + classes, so async/await downlevels to a
          // self-contained _asyncToGenerator helper — no regenerator runtime,
          // which matters because the bridge runs before any app bundle loads.
          targets: { chrome: "51" },
          bugfixes: true,
          modules: false,
          loose: true,
        },
      ],
    ],
  });

  const code = `// AUTO-GENERATED by scripts/build-legacy-bridge.mjs (v2.11.29).
// ES5 downlevel of @capacitor/android native-bridge.js for WebView 51.
// Do not edit by hand — regenerated on every build.
${result.code}
`;

  // Hard gate: never emit something WebView 51 cannot parse.
  // Chromium 51 is ES2015-complete (class, let/const, generators, destructuring,
  // spread); what it lacks is ES2016+ — async/await, exponent, object rest.
  // So ES2015 is the correct parse target for the bridge.
  acorn.parse(code, { ecmaVersion: 2015 });


  mkdirSync(dirname(TARGET), { recursive: true });
  writeFileSync(TARGET, code, "utf8");

  if (!silent) {
    console.log(
      `[legacy-bridge] native-bridge.js downlevelled to ES5 -> android/app/src/main/assets/ (${code.length} bytes)`
    );
  }

  return { skipped: false, bytes: code.length };
}

// Allow direct execution: `node scripts/build-legacy-bridge.mjs`
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  buildLegacyBridge().catch((error) => {
    console.error("[legacy-bridge] FAILED:", error);
    process.exit(1);
  });
}
